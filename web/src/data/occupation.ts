/** 落库值：有二级岗位就用「行业 · 岗位」，否则就是行业本身 */
export function occupationValue(industry: string, role?: string): string {
  return role ? `${industry} · ${role}` : industry;
}

/** 把落库值拆回「行业 / 岗位」，用于重新打开时定位 */
export function parseOccupation(value: string): { industry: string | null; role: string | null } {
  const i = value.indexOf(" · ");
  if (i < 0) {
    // 单段：可能正好是一个行业名（学生/其他），也可能是改造前的旧值（「互联网」）
    return INDUSTRIES.some((x) => x.name === value) ? { industry: value, role: null } : { industry: null, role: value };
  }
  return { industry: value.slice(0, i), role: value.slice(i + 3) };
}
